"""
Deterministic aerodynamic calculations.
Formulas for lift, drag, pressure coefficients, and boundary layer estimates.
"""
import math
import uuid
from typing import Optional, List
from engineering_engine.constants import RHO_STANDARD_SL
from engineering_engine.exceptions import ValidationError
from engineering_engine.units import convert_to_si
from engineering_engine.validators import validate_positive
from engineering_engine.result_models import CalculationResult

def calculate_lift_coefficient(
    lift_force: float,
    reference_area: float,
    dynamic_pressure: Optional[float] = None,
    density: Optional[float] = None,
    velocity: Optional[float] = None,
    force_unit: str = "N",
    area_unit: str = "m^2"
) -> CalculationResult:
    """
    Governing Equation:
        C_L = L / (q * S) = L / (0.5 * rho * U^2 * S)
    """
    l_si = convert_to_si(lift_force, force_unit, "force")
    s_si = validate_positive("reference_area", convert_to_si(reference_area, area_unit, "area"), strict=True)

    if dynamic_pressure is not None:
        q_si = validate_positive("dynamic_pressure", dynamic_pressure, strict=True)
        converted = {"lift_force_N": l_si, "reference_area_m2": s_si, "dynamic_pressure_Pa": q_si}
        formula_str = "C_L = L / (q * S)"
    else:
        if density is None or velocity is None:
            raise ValidationError("Either dynamic_pressure or both density and velocity must be provided.")
        rho_si = validate_positive("density", density, strict=True)
        u_si = validate_positive("velocity", velocity, strict=True)
        q_si = 0.5 * rho_si * (u_si ** 2)
        converted = {"lift_force_N": l_si, "reference_area_m2": s_si, "density_kg_m3": rho_si, "velocity_m_s": u_si, "dynamic_pressure_Pa": q_si}
        formula_str = "C_L = L / (0.5 * rho * U^2 * S)"

    cl = l_si / (q_si * s_si)

    return CalculationResult(
        calculation_id=str(uuid.uuid4()),
        calculation_name="Lift Coefficient",
        formula=formula_str,
        inputs={"lift_force": lift_force, "reference_area": reference_area, "dynamic_pressure": dynamic_pressure},
        input_units={"lift_force": force_unit, "reference_area": area_unit},
        converted_inputs=converted,
        result=float(cl),
        output_unit="dimensionless",
        assumptions=[
            "Force is perpendicular to freestream velocity vector",
            "Reference area corresponds to planform wing area"
        ],
        applicability="Quantifies non-dimensional lift force generated by a body in a fluid stream."
    )

def calculate_drag_coefficient(
    drag_force: float,
    reference_area: float,
    dynamic_pressure: Optional[float] = None,
    density: Optional[float] = None,
    velocity: Optional[float] = None,
    force_unit: str = "N",
    area_unit: str = "m^2"
) -> CalculationResult:
    """
    Governing Equation:
        C_D = D / (q * S) = D / (0.5 * rho * U^2 * S)
    """
    d_si = validate_positive("drag_force", convert_to_si(drag_force, force_unit, "force"), strict=False)
    s_si = validate_positive("reference_area", convert_to_si(reference_area, area_unit, "area"), strict=True)

    if dynamic_pressure is not None:
        q_si = validate_positive("dynamic_pressure", dynamic_pressure, strict=True)
        converted = {"drag_force_N": d_si, "reference_area_m2": s_si, "dynamic_pressure_Pa": q_si}
        formula_str = "C_D = D / (q * S)"
    else:
        if density is None or velocity is None:
            raise ValidationError("Either dynamic_pressure or both density and velocity must be provided.")
        rho_si = validate_positive("density", density, strict=True)
        u_si = validate_positive("velocity", velocity, strict=True)
        q_si = 0.5 * rho_si * (u_si ** 2)
        converted = {"drag_force_N": d_si, "reference_area_m2": s_si, "density_kg_m3": rho_si, "velocity_m_s": u_si, "dynamic_pressure_Pa": q_si}
        formula_str = "C_D = D / (0.5 * rho * U^2 * S)"

    cd = d_si / (q_si * s_si)

    return CalculationResult(
        calculation_id=str(uuid.uuid4()),
        calculation_name="Drag Coefficient",
        formula=formula_str,
        inputs={"drag_force": drag_force, "reference_area": reference_area, "dynamic_pressure": dynamic_pressure},
        input_units={"drag_force": force_unit, "reference_area": area_unit},
        converted_inputs=converted,
        result=float(cd),
        output_unit="dimensionless",
        assumptions=[
            "Force is parallel to the incoming freestream flow direction",
            "Reference area typically frontal projected area for bluff bodies or planform area for lifting surfaces"
        ],
        applicability="Quantifies non-dimensional aerodynamic drag opposing body motion."
    )

def calculate_pressure_coefficient(
    surface_pressure: float,
    freestream_pressure: float,
    freestream_dynamic_pressure: float
) -> CalculationResult:
    """
    Governing Equation:
        C_p = (p - p_inf) / q_inf
    """
    q_inf = validate_positive("freestream_dynamic_pressure", freestream_dynamic_pressure, strict=True)
    cp = (surface_pressure - freestream_pressure) / q_inf

    warnings = []
    if cp > 1.0001:
        warnings.append(f"Incompressible stagnation Cp exceeds 1.0 (got {cp:.4f}). Indicates supersonic compression or numerical overshoot.")

    return CalculationResult(
        calculation_id=str(uuid.uuid4()),
        calculation_name="Pressure Coefficient",
        formula="C_p = (p - p_inf) / q_inf",
        inputs={
            "surface_pressure": surface_pressure,
            "freestream_pressure": freestream_pressure,
            "freestream_dynamic_pressure": freestream_dynamic_pressure
        },
        input_units={"pressure": "Pa"},
        converted_inputs={
            "p_Pa": surface_pressure,
            "p_inf_Pa": freestream_pressure,
            "q_inf_Pa": q_inf
        },
        result=float(cp),
        output_unit="dimensionless",
        assumptions=["Incompressible / subsonic freestream reference pressure"],
        applicability="Relates local static pressure variation to dynamic pressure head.",
        warnings=warnings
    )

def estimate_first_cell_height_y_plus(
    target_y_plus: float,
    velocity: float,
    chord_length: float,
    density: float = RHO_STANDARD_SL,
    dynamic_viscosity: float = 1.7894e-5
) -> CalculationResult:
    """
    Estimates required first-layer cell height (y) for a target y+ using flat-plate boundary layer theory.
    Governing Formulas:
        Re_x = rho * U * L / mu
        C_f = 0.058 * Re_x^(-0.2)  (Prandtl / Schlichting turbulent boundary layer)
        tau_w = 0.5 * C_f * rho * U^2
        u_tau = sqrt(tau_w / rho)
        y = (y+ * mu) / (rho * u_tau)
    """
    yp = validate_positive("target_y_plus", target_y_plus, strict=True)
    u = validate_positive("velocity", velocity, strict=True)
    l = validate_positive("chord_length", chord_length, strict=True)
    rho = validate_positive("density", density, strict=True)
    mu = validate_positive("dynamic_viscosity", dynamic_viscosity, strict=True)

    re_x = (rho * u * l) / mu
    cf = 0.058 * (re_x ** -0.2)
    tau_w = 0.5 * cf * rho * (u ** 2)
    u_tau = math.sqrt(tau_w / rho)
    y_first = (yp * mu) / (rho * u_tau)

    return CalculationResult(
        calculation_id=str(uuid.uuid4()),
        calculation_name="First Cell Height Estimation (y+)",
        formula="y = (y+ * mu) / (rho * sqrt(0.5 * (0.058 * Re^(-0.2)) * rho * U^2 / rho))",
        inputs={"target_y_plus": target_y_plus, "velocity": velocity, "chord_length": chord_length},
        input_units={"target_y_plus": "dimensionless", "velocity": "m/s", "chord_length": "m"},
        converted_inputs={"Re_x": re_x, "Cf": cf, "tau_w_Pa": tau_w, "u_tau_m_s": u_tau},
        result=float(y_first),
        output_unit="m",
        assumptions=[
            "Fully turbulent flat-plate boundary layer correlation (Schlichting)",
            "Zero pressure gradient external flow",
            "Near-wall linear viscous sublayer approximation (u+ = y+)"
        ],
        applicability="Recommended starting estimate for CFD prism layer / boundary layer mesh sizing."
    )
